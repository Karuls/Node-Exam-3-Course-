// WebSocket сервер с ping/pong
const WebSocket = require('ws');

console.log('=== WebSocket сервер с ping/pong ===\n');

// Создаем WebSocket сервер
const wss = new WebSocket.Server({ port: 8080 });

console.log('Сервер запущен на ws://localhost:8080\n');

// Счетчик подключений
let connectionCount = 0;

wss.on('connection', (ws) => {
    connectionCount++;
    const clientId = connectionCount;
    
    console.log(`Клиент #${clientId} подключился`);
    ws.send(`Вы клиент #${clientId}. Всего клиентов: ${wss.clients.size}`);
    
    // Настройка ping/pong
    let isAlive = true;
    
    function heartbeat() {
        isAlive = true;
    }
    
    ws.on('pong', heartbeat);
    
    // Периодическая проверка соединения
    const interval = setInterval(() => {
        if (!isAlive) {
            console.log(`Клиент #${clientId} не отвечает, отключаем...`);
            return ws.terminate();
        }
        
        isAlive = false;
        ws.ping();
    }, 30000); // Каждые 30 секунд
    
    // Обработка сообщений
    ws.on('message', (message) => {
        const msg = message.toString();
        console.log(`Клиент #${clientId}: ${msg}`);
        
        // Отправляем эхо
        ws.send(`Эхо: ${msg}`);
        
        // Рассылаем другим клиентам
        wss.clients.forEach((client) => {
            if (client !== ws && client.readyState === WebSocket.OPEN) {
                client.send(`Клиент #${clientId}: ${msg}`);
            }
        });
    });
    
    // Обработка отключения
    ws.on('close', () => {
        clearInterval(interval);
        console.log(`Клиент #${clientId} отключился`);
    });
    
    ws.on('error', (error) => {
        console.log(`Ошибка у клиента #${clientId}:`, error.message);
    });
});

console.log('=== Инструкция для клиента ===');
console.log('Запустите клиентский скрипт: node client.js');
console.log('\n=== Тестирование ping/pong ===');
console.log('Сервер будет отправлять ping каждые 30 секунд');
